type LocaleKey = keyof typeof copyByLocale;

type PageProps = {
  params: Promise<{
    locale: string;
  }>;
};

function resolveLocale(locale: string): LocaleKey {
  const normalized = locale.toLowerCase();

  if (normalized === 'zh' || normalized === 'zh-cn' || normalized === 'zh_hans') {
    return 'zh-hans';
  }

  if (normalized in copyByLocale) {
    return normalized as LocaleKey;
  }

  return 'en';
}

